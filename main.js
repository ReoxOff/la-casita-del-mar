document.addEventListener('DOMContentLoaded', () => {
  const header = document.getElementById('siteHeader');
  const menuToggle = document.querySelector('.menu-toggle');
  const navOverlay = document.getElementById('navOverlay');
  const navLinks = document.querySelectorAll('.nav-link');
  const yearSpan = document.getElementById('currentYear');
  const langButtons = document.querySelectorAll('.lang-btn');
  const waLinks = document.querySelectorAll('.wa-link');

  if (yearSpan) {
    yearSpan.textContent = new Date().getFullYear();
  }

  const applyLanguage = (lang) => {
    const dict = translations[lang] || translations.es;
    document.documentElement.lang = lang;
    document.title = dict.page_title;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const key = el.getAttribute('data-i18n-alt');
      if (dict[key]) {
        el.setAttribute('alt', dict[key]);
      }
    });

    const encodedMsg = encodeURIComponent(dict.wa_message);
    waLinks.forEach(link => {
      link.href = `https://wa.me/34659399207?text=${encodedMsg}`;
    });

    langButtons.forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    try {
      localStorage.setItem('casita_lang', lang);
    } catch (e) {}
  };

  langButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      const selectedLang = btn.getAttribute('data-lang');
      applyLanguage(selectedLang);
    });
  });

  let initialLang = 'es';
  try {
    const saved = localStorage.getItem('casita_lang');
    if (saved && translations[saved]) {
      initialLang = saved;
    } else {
      const browserLang = navigator.language.slice(0, 2).toLowerCase();
      if (translations[browserLang]) initialLang = browserLang;
    }
  } catch (e) {}
  applyLanguage(initialLang);

  const fadeObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, {
    rootMargin: '0px 0px -8% 0px',
    threshold: 0.05
  });

  document.querySelectorAll('.animate-fade').forEach(el => fadeObserver.observe(el));

  const handleScroll = () => {
    header.classList.toggle('scrolled', window.scrollY > 40);
  };
  window.addEventListener('scroll', handleScroll, { passive: true });
  handleScroll();

  const toggleMenu = (forceClose = false) => {
    if (!menuToggle) return;
    const isExpanded = menuToggle.getAttribute('aria-expanded') === 'true';
    const nextState = forceClose ? false : !isExpanded;
    
    menuToggle.setAttribute('aria-expanded', String(nextState));
    header.classList.toggle('nav-active', nextState);
    document.body.classList.toggle('menu-open', nextState);
    if (navOverlay) navOverlay.classList.toggle('active', nextState);
  };

  if (menuToggle) {
    menuToggle.addEventListener('click', () => toggleMenu());
  }

  if (navOverlay) {
    navOverlay.addEventListener('click', () => toggleMenu(true));
  }

  navLinks.forEach(link => {
    link.addEventListener('click', () => toggleMenu(true));
  });

  const sections = document.querySelectorAll('main section[id]');
  const scrollSpyObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const id = entry.target.getAttribute('id');
        navLinks.forEach(link => {
          link.classList.toggle('active', link.getAttribute('href') === `#${id}`);
        });
      }
    });
  }, {
    rootMargin: '-35% 0px -55% 0px'
  });

  sections.forEach(section => scrollSpyObserver.observe(section));

  const images = document.querySelectorAll('.media-container img, .gallery-card img');
  const markImageLoaded = (img) => {
    img.classList.add('loaded');
    if (img.parentElement) {
      img.parentElement.classList.add('is-loaded');
    }
  };

  images.forEach(img => {
    if (img.complete) {
      markImageLoaded(img);
    } else {
      img.addEventListener('load', () => markImageLoaded(img), { once: true });
    }
  });

  const lightbox = document.getElementById('lightbox');
  const lightboxImg = document.getElementById('lightboxImg');
  const lightboxCaption = document.getElementById('lightboxCaption');
  const lightboxClose = document.getElementById('lightboxClose');
  const galleryCards = document.querySelectorAll('.gallery-card');

  const openLightbox = (card) => {
    const img = card.querySelector('img');
    const caption = card.querySelector('.gallery-caption');
    if (!img || !lightbox) return;

    lightboxImg.src = img.src;
    lightboxImg.alt = img.alt;
    lightboxCaption.textContent = caption ? caption.textContent : img.alt;
    lightbox.classList.add('active');
    lightbox.setAttribute('aria-hidden', 'false');
    document.body.classList.add('menu-open');
  };

  const closeLightbox = () => {
    if (!lightbox) return;
    lightbox.classList.remove('active');
    lightbox.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('menu-open');
    setTimeout(() => { lightboxImg.src = ''; }, 300);
  };

  galleryCards.forEach(card => {
    card.addEventListener('click', () => openLightbox(card));
    card.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        openLightbox(card);
      }
    });
  });

  if (lightboxClose) lightboxClose.addEventListener('click', closeLightbox);
  if (lightbox) {
    lightbox.addEventListener('click', (e) => {
      if (e.target === lightbox) closeLightbox();
    });
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      closeLightbox();
      toggleMenu(true);
    }
  });
});